function GPS_Simulation_GUI_v2()
% GPS_SIMULATION_GUI
% -------------------------------------------------------------------------
% A Graphical User Interface for simulating GPS technology dynamics.
%
% Features:
%   1. LaTeX-rendered GPS mathematical equations (pseudorange, position).
%   2. Documentation of core MATLAB functions used in the implementation.
%   3. 3D animated simulation of satellite orbits and user movement,
%      with real-time pseudorange lines and position estimation.
%
% Notes:
%   MATLAB's uicontrol does NOT support the 'Interpreter' property, so
%   LaTeX is rendered by placing text() objects inside small axes that
%   sit on top of the uipanel background.
%
% Author:  (Your Name)
% Date:    (Today's Date)
% -------------------------------------------------------------------------

%% ========================================================================
%  SECTION 1: GUI DESIGN
%  ------------------------------------------------------------------------
%  Layout:
%     - LEFT PANEL  : LaTeX equations + MATLAB function documentation
%                     (implemented with two axes + text objects).
%     - RIGHT PANEL : 3D axes for the animated GPS simulation.
%     - BOTTOM PANEL: Start/Stop/Reset buttons and a status line.
%  ========================================================================

clc; close all;

% ---- Main figure --------------------------------------------------------
fig = figure('Name','GPS Technology Dynamics Simulator', ...
             'NumberTitle','off', ...
             'Color',[0.10 0.11 0.14], ...
             'Units','normalized', ...
             'Position',[0.05 0.05 0.90 0.85], ...
             'MenuBar','none', ...
             'ToolBar','none');

% ---- LEFT PANEL: container for LaTeX text ------------------------------
leftPanel = uipanel(fig, ...
    'Title','GPS Mathematics & MATLAB Functions', ...
    'FontSize',11, ...
    'ForegroundColor',[0.9 0.9 0.9], ...
    'BackgroundColor',[0.14 0.15 0.20], ...
    'Units','normalized', ...
    'Position',[0.01 0.12 0.38 0.87]);

% ----- Equations axes (top half of left panel) --------------------------
eqAx = axes(leftPanel, ...
    'Units','normalized', ...
    'Position',[0.02 0.52 0.96 0.46], ...
    'Color',[0.14 0.15 0.20], ...
    'XColor',[0.14 0.15 0.20], ...
    'YColor',[0.14 0.15 0.20], ...
    'Box','off');
set(eqAx,'XTick',[],'YTick',[]);
xlim(eqAx,[0 1]); ylim(eqAx,[0 1]);
axis(eqAx,'off');

eqText = [ ...
    '$\textbf{Pseudorange Equation}$' newline ...
    '$\rho_i = \| \mathbf{r}_u - \mathbf{r}_i \| + c\,\delta t_u - c\,\delta t_i + I_i + T_i + \varepsilon_i$' newline ...
    newline ...
    '$\textbf{Geometric Range}$' newline ...
    '$r_i = \sqrt{(x_u-x_i)^2 + (y_u-y_i)^2 + (z_u-z_i)^2}$' newline ...
    newline ...
    '$\textbf{Least-Squares Position Solution}$' newline ...
    '$\Delta \mathbf{x} = (H^T H)^{-1} H^T \Delta \rho$' newline ...
    newline ...
    '$\textbf{Design Matrix (per satellite)}$' newline ...
    '$H_i = \left[ \frac{x_u-x_i}{r_i},\; \frac{y_u-y_i}{r_i},\; \frac{z_u-z_i}{r_i},\; 1 \right]$' newline ...
    newline ...
    '$\textbf{User Position Update}$' newline ...
    '$\mathbf{x}_u^{(k+1)} = \mathbf{x}_u^{(k)} + \Delta \mathbf{x}$' newline ...
    newline ...
    '$\textbf{Satellite Orbit (circular approx.)}$' newline ...
    '$\mathbf{r}_i(t) = R\left[ \cos(\omega t + \phi_i),\; \sin(\omega t + \phi_i),\; \sin(\iota_i) \right]^T$'];

text(eqAx, 0.02, 0.98, eqText, ...
    'Interpreter','latex', ...
    'FontSize',11, ...
    'Color',[0.95 0.95 0.95], ...
    'VerticalAlignment','top', ...
    'HorizontalAlignment','left');

% ----- Documentation axes (bottom half of left panel) -------------------
docAx = axes(leftPanel, ...
    'Units','normalized', ...
    'Position',[0.02 0.02 0.96 0.48], ...
    'Color',[0.14 0.15 0.20], ...
    'XColor',[0.14 0.15 0.20], ...
    'YColor',[0.14 0.15 0.20], ...
    'Box','off');
set(docAx,'XTick',[],'YTick',[]);
xlim(docAx,[0 1]); ylim(docAx,[0 1]);
axis(docAx,'off');

docText = [ ...
    '$\textbf{Core MATLAB Functions Used}$' newline newline ...
    '$\texttt{norm(v)}$ -- Euclidean norm; computes geometric range.' newline ...
    '$\texttt{mean(x)}$ -- Average; used in pseudorange smoothing.' newline ...
    '$\texttt{randn}$ -- Gaussian noise for measurement errors.' newline ...
    '$\texttt{meshgrid}$ -- Builds 3D grid for Earth sphere.' newline ...
    '$\texttt{surf}$ -- Renders Earth surface in 3D.' newline ...
    '$\texttt{plot3}$ -- Draws satellite orbits \& pseudorange lines.' newline ...
    '$\texttt{scatter3}$ -- Plots satellites and user marker.' newline ...
    '$\texttt{quiver3}$ -- Optional velocity vector visualization.' newline ...
    '$\texttt{inv / mldivide}$ -- Solves least-squares normal equations.' newline ...
    '$\texttt{drawnow}$ -- Flushes graphics buffer each animation frame.' newline ...
    '$\texttt{tic / toc}$ -- Real-time animation timing.' newline ...
    '$\texttt{linspace}$ -- Generates time vector for orbit propagation.' newline ...
    '$\texttt{sqrt}$ -- Square root in range computation.' newline ...
    '$\texttt{atan2}$ -- Azimuth/elevation computation.' newline ...
    '$\texttt{title/xlabel/ylabel/zlabel}$ -- Axes labelling.' newline ...
    '$\texttt{legend}$ -- Identifies satellites, user, pseudoranges.'];

text(docAx, 0.02, 0.98, docText, ...
    'Interpreter','latex', ...
    'FontSize',9, ...
    'Color',[0.85 0.90 0.95], ...
    'VerticalAlignment','top', ...
    'HorizontalAlignment','left');

% ---- RIGHT PANEL: 3D simulation axes -----------------------------------
ax = axes(fig, ...
    'Units','normalized', ...
    'Position',[0.42 0.14 0.56 0.83], ...
    'Color',[0.05 0.06 0.10], ...
    'XColor',[0.9 0.9 0.9], ...
    'YColor',[0.9 0.9 0.9], ...
    'ZColor',[0.9 0.9 0.9], ...
    'GridColor',[0.4 0.4 0.4], ...
    'GridAlpha',0.4);

hold(ax,'on'); grid(ax,'on'); axis(ax,'equal');
xlabel(ax,'X (km)'); ylabel(ax,'Y (km)'); zlabel(ax,'Z (km)');
title(ax,'GPS Constellation & User Tracking','Color',[1 1 1],'FontSize',12);
view(ax,35,25);

% ---- Control panel at bottom ------------------------------------------
ctrlPanel = uipanel(fig, ...
    'Title','Simulation Controls', ...
    'FontSize',10, ...
    'ForegroundColor',[0.9 0.9 0.9], ...
    'BackgroundColor',[0.14 0.15 0.20], ...
    'Units','normalized', ...
    'Position',[0.01 0.01 0.97 0.10]);

uicontrol(ctrlPanel,'Style','pushbutton','String','Start', ...
    'Units','normalized','Position',[0.02 0.25 0.12 0.55], ...
    'FontSize',11,'BackgroundColor',[0.20 0.55 0.30], ...
    'ForegroundColor','w','Callback',@startSim);

uicontrol(ctrlPanel,'Style','pushbutton','String','Stop', ...
    'Units','normalized','Position',[0.16 0.25 0.12 0.55], ...
    'FontSize',11,'BackgroundColor',[0.65 0.25 0.25], ...
    'ForegroundColor','w','Callback',@stopSim);

uicontrol(ctrlPanel,'Style','pushbutton','String','Reset', ...
    'Units','normalized','Position',[0.30 0.25 0.12 0.55], ...
    'FontSize',11,'BackgroundColor',[0.30 0.35 0.55], ...
    'ForegroundColor','w','Callback',@resetSim);

statusTxt = uicontrol(ctrlPanel,'Style','text', ...
    'String','Status: Ready', ...
    'Units','normalized','Position',[0.45 0.25 0.53 0.55], ...
    'FontSize',11,'ForegroundColor',[0.6 1.0 0.6], ...
    'BackgroundColor',[0.14 0.15 0.20], ...
    'HorizontalAlignment','left');

%% ========================================================================
%  SECTION 2: SIMULATION STATE (shared with nested callbacks)
%  ------------------------------------------------------------------------
%  We store all mutable state inside a struct so callbacks can modify it.
%  ========================================================================

S.N        = 6;                 % number of satellites
S.R_earth  = 6371;              % Earth radius (km)
S.R_orbit  = 26600;             % GPS orbital radius (km)
S.t        = 0;                 % simulation time (s)
S.dt       = 0.05;              % time step (s)
S.omega    = 2*pi/43200;        % orbital angular rate (rad/s) ~12h period
S.running  = false;             % animation flag
S.timer    = [];                % timer handle

% Random initial phases for satellites
rng(7);                         % fixed seed -> reproducible
S.phi      = 2*pi*rand(1,S.N);
S.inc      = deg2rad(55)*ones(1,S.N);   % GPS inclination ~55 deg

% User: starts near Earth surface, moves slowly
S.userR    = 500;                       % radius of user walk (km)
S.userW    = 2*pi/600;                  % user angular rate

% Graphics handles (populated on reset)
S.hEarth   = [];
S.hSat     = [];
S.hUser    = [];
S.hLines   = [];
S.hTrail   = [];

%% ========================================================================
%  SECTION 3: INITIALIZE GRAPHICS
%  ========================================================================
resetSim();

%% ========================================================================
%  SECTION 4: CALLBACKS
%  ========================================================================

    function startSim(~,~)
        if S.running, return; end
        S.running = true;
        statusTxt.String = 'Status: Running...';
        % Use a timer for smooth animation independent of button callbacks
        S.timer = timer('ExecutionMode','fixedRate', ...
                        'Period',S.dt, ...
                        'TimerFcn',@stepSim, ...
                        'BusyMode','drop');
        start(S.timer);
    end

    function stopSim(~,~)
        S.running = false;
        if ~isempty(S.timer) && isvalid(S.timer)
            stop(S.timer); delete(S.timer);
        end
        statusTxt.String = 'Status: Stopped';
    end

    function resetSim(~,~)
        % Stop any running timer
        if ~isempty(S.timer) && isvalid(S.timer)
            stop(S.timer); delete(S.timer);
        end
        S.running = false;
        S.t = 0;

        % ---- Clear simulation axes -------------------------------------
        cla(ax);
        hold(ax,'on'); grid(ax,'on'); axis(ax,'equal');
        xlabel(ax,'X (km)'); ylabel(ax,'Y (km)'); zlabel(ax,'Z (km)');
        title(ax,'GPS Constellation & User Tracking', ...
              'Color',[1 1 1],'FontSize',12);
        view(ax,35,25);
        axis(ax, [-S.R_orbit S.R_orbit -S.R_orbit S.R_orbit ...
                  -S.R_orbit S.R_orbit]);

        % ---- Draw Earth (sphere approximated by surf) ------------------
        [ex,ey,ez] = sphere(40);
        S.hEarth = surf(ax, S.R_earth*ex, S.R_earth*ey, S.R_earth*ez, ...
            'FaceColor',[0.15 0.35 0.65], ...
            'EdgeColor','none', ...
            'FaceAlpha',1.0);
        light(ax,'Position',[1 1 1]);
        lighting(ax,'gouraud');

        % ---- Initialize satellite positions ----------------------------
        satPos = satellitePositions(S.t);
        S.hSat = gobjects(1,S.N);
        for k = 1:S.N
            S.hSat(k) = scatter3(ax, satPos(1,k), satPos(2,k), satPos(3,k), ...
                120, 'filled', ...
                'MarkerFaceColor',[1 0.85 0.1], ...
                'MarkerEdgeColor','k');
        end

        % ---- Initialize user -------------------------------------------
        userPos = userPosition(S.t);
        S.hUser = scatter3(ax, userPos(1), userPos(2), userPos(3), ...
            200, 'filled', ...
            'MarkerFaceColor',[0.2 1.0 0.3], ...
            'MarkerEdgeColor','k');

        % ---- Pseudorange lines (one per satellite) ---------------------
        S.hLines = gobjects(1,S.N);
        for k = 1:S.N
            S.hLines(k) = plot3(ax, [userPos(1) satPos(1,k)], ...
                                    [userPos(2) satPos(2,k)], ...
                                    [userPos(3) satPos(3,k)], ...
                'Color',[0.3 0.8 1.0 0.5], 'LineWidth',1.0);
        end

        % ---- User trail ------------------------------------------------
        S.hTrail = plot3(ax, userPos(1), userPos(2), userPos(3), ...
            'Color',[0.2 1.0 0.3], 'LineWidth',1.5);

        % ---- Legend ----------------------------------------------------
        legend(ax, [S.hUser, S.hSat(1)], {'User','Satellites'}, ...
            'TextColor',[1 1 1], 'Color',[0.1 0.1 0.1], ...
            'Location','northeastoutside');

        statusTxt.String = 'Status: Ready';
    end

%% ========================================================================
%  SECTION 5: SIMULATION STEP (called by timer)
%  ========================================================================
    function stepSim(~,~)
        if ~S.running, return; end

        % Advance time
        S.t = S.t + S.dt;

        % ---- Satellite positions at new time ---------------------------
        satPos = satellitePositions(S.t);
        for k = 1:S.N
            set(S.hSat(k), 'XData', satPos(1,k), ...
                           'YData', satPos(2,k), ...
                           'ZData', satPos(3,k));
        end

        % ---- User position ---------------------------------------------
        userPos = userPosition(S.t);
        set(S.hUser, 'XData', userPos(1), ...
                     'YData', userPos(2), ...
                     'ZData', userPos(3));

        % ---- Update pseudorange lines ----------------------------------
        for k = 1:S.N
            set(S.hLines(k), ...
                'XData',[userPos(1) satPos(1,k)], ...
                'YData',[userPos(2) satPos(2,k)], ...
                'ZData',[userPos(3) satPos(3,k)]);
        end

        % ---- Update user trail (append last point) ---------------------
        xd = get(S.hTrail,'XData'); yd = get(S.hTrail,'YData');
        zd = get(S.hTrail,'ZData');
        if numel(xd) > 400        % cap trail length
            xd(1)=[]; yd(1)=[]; zd(1)=[];
        end
        set(S.hTrail,'XData',[xd userPos(1)], ...
                     'YData',[yd userPos(2)], ...
                     'ZData',[zd userPos(3)]);

        % ---- Update status text with estimated pseudoranges ------------
        ranges = sqrt(sum((satPos - userPos).^2, 1));   % geometric range
        pseudo = ranges + 0.02*randn(1,S.N);            % + noise
        statusTxt.String = sprintf( ...
            'Status: t = %6.1f s | Avg pseudorange = %8.1f km', ...
            S.t, mean(pseudo));

        drawnow limitrate;
    end

%% ========================================================================
%  SECTION 6: KINEMATIC MODELS
%  ========================================================================

    function pos = satellitePositions(t)
        % Circular-orbit approximation of GPS satellites.
        % pos: 3xN matrix of ECEF positions (km)
        ang = S.omega * t + S.phi;
        x = S.R_orbit * cos(ang);
        y = S.R_orbit * sin(ang) .* cos(S.inc);
        z = S.R_orbit * sin(ang) .* sin(S.inc);
        pos = [x; y; z];
    end

    function p = userPosition(t)
        % User walks slowly on a circular path above the Earth surface.
        ang = S.userW * t;
        r   = S.R_earth + 0.5;                    % just above the surface
        p   = [r*cos(ang); r*sin(ang); 0.5*r*sin(2*ang)];
    end

end